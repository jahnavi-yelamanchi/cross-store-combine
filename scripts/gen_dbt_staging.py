"""Generate dbt sources, staging models and policy vars from stores/mappings and policy.yaml.

Usage: uv run python scripts/gen_dbt_staging.py [--check]
"""

from __future__ import annotations

import argparse
import sys
import types
import typing
from collections import Counter
from datetime import datetime
from decimal import Decimal
from pathlib import Path

import duckdb
import yaml

from xstore.entities.mapping import LB_PER_KG, EntityMapping, all_stores, load_mapping
from xstore.entities.models import ENTITY_TYPES

ROOT = Path(__file__).resolve().parents[1]
DBT = ROOT / "dbt"
SNAPSHOT = "evals/frozen/v1"
PLURAL = {"customer": "customers", "order": "orders", "batch": "batches"}
SQL_TYPES: dict[object, str] = {
    Decimal: "decimal(18, 2)",
    int: "bigint",
    float: "double",
    datetime: "timestamptz",
}
# json_type() results grouped so int-vs-uint is not reported as drift.
JSON_CLASS = {
    "UBIGINT": ("UBIGINT", "BIGINT"),
    "BIGINT": ("UBIGINT", "BIGINT"),
    "DOUBLE": ("DOUBLE",),
    "VARCHAR": ("VARCHAR",),
    "BOOLEAN": ("BOOLEAN",),
}
HEADER = "-- Generated by scripts/gen_dbt_staging.py from stores/mappings; do not edit.\n"


def sql_type(entity_type: str, field: str) -> str:
    ann = ENTITY_TYPES[entity_type].model_fields[field].annotation
    if isinstance(ann, types.UnionType) or typing.get_origin(ann) is typing.Union:
        ann = next(a for a in typing.get_args(ann) if a is not type(None))
    return SQL_TYPES.get(ann, "varchar")


def expected_json_types(path: Path, natives: list[str]) -> dict[str, tuple[str, ...]]:
    """Most common json_type per native field in the snapshot (the store's declared type)."""
    con = duckdb.connect()
    out: dict[str, tuple[str, ...]] = {}
    for native in natives:
        rows = con.execute(
            "select json_type(json, ?) from read_json_objects(?, format='newline_delimited')",
            [f'$."{native}"', str(path)],
        ).fetchall()
        counts = Counter(r[0] for r in rows if r[0] not in (None, "NULL"))
        if counts:
            out[native] = JSON_CLASS.get(
                counts.most_common(1)[0][0], (counts.most_common(1)[0][0],)
            )
    return out


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def field_expr(entity_type: str, field: str, m: EntityMapping) -> str:
    native = m.fields[field]
    raw = f"json ->> {q(native)}"
    typ = sql_type(entity_type, field)
    unit = m.units.get(field)
    if unit == "cents":
        return f"cast(try_cast({raw} as decimal(18, 0)) / 100 as {typ})"
    if unit == "lb":
        return f"try_cast({raw} as double) / {LB_PER_KG}"
    if field == ENTITY_TYPES[entity_type].key_field and m.key_prefix:
        p = m.key_prefix
        return f"case when starts_with({raw}, {q(p)}) then ({raw})[{len(p) + 1}:] else {raw} end"
    if field in m.values:
        cases = " ".join(f"when {q(k)} then {q(v)}" for k, v in m.values[field].items())
        return f"case trim({raw}) {cases} else trim({raw}) end"
    if typ != "varchar":
        return f"try_cast({raw} as {typ})"
    if (entity_type, field) == ("customer", "email"):
        return f"lower(trim({raw}))"
    return f"trim({raw})"


def drift_expr(entity_type: str, field: str, m: EntityMapping, expected: tuple[str, ...]) -> str:
    native = m.fields[field]
    allowed = ", ".join(q(t) for t in ("NULL", *expected))
    check = f"coalesce(json_type(json, {q(f'$."{native}"')}), 'NULL') not in ({allowed})"
    if sql_type(entity_type, field) == "varchar" or m.units.get(field):
        return check
    # Value present but not castable is drift too.
    cast = field_expr(entity_type, field, m)
    return f"{check} or (json ->> {q(native)} is not null and {cast} is null)"


def staging_sql(store: str, entity_type: str, m: EntityMapping, snapshot: Path) -> str:
    path = snapshot / store / f"{entity_type}.jsonl"
    expected = expected_json_types(path, list(m.fields.values()))
    cols = [f"    {field_expr(entity_type, f, m)} as {f}" for f in m.fields]
    drifts = [
        f"        ({drift_expr(entity_type, f, m, expected[m.fields[f]])})"
        for f in m.fields
        if m.fields[f] in expected
    ]
    body = ",\n".join(cols)
    drift = "\n        or ".join(d.strip() for d in drifts) if drifts else "false"
    return (
        f"{HEADER}select\n    {q(store)} as _store,\n{body},\n"
        f"    ({drift}) as _type_drift\n"
        f"from {{{{ source({q(store)}, {q(entity_type)}) }}}}\n"
    )


def holdings(snapshot: Path) -> dict[str, list[str]]:
    """entity_type -> stores that have both a mapping and snapshot data."""
    out: dict[str, list[str]] = {}
    for store in all_stores():
        for entity_type in load_mapping(store).entities:
            if (snapshot / store / f"{entity_type}.jsonl").exists():
                out.setdefault(entity_type, []).append(store)
    return out


def policy_vars(held: dict[str, list[str]]) -> dict[str, object]:
    policy = yaml.safe_load((ROOT / "policy" / "policy.yaml").read_text())
    priority: dict[str, dict[str, list[str]]] = {}
    for entity_type, stores in held.items():
        default = policy["defaults"][entity_type]["source_priority"]
        rules = {"_default": [s for s in default if s in stores]}
        for field, rule in policy.get("field_overrides", {}).get(entity_type, {}).items():
            rules[field] = [s for s in rule["source_priority"] if s in stores]
        priority[entity_type] = rules
    return {"snapshot_dir": SNAPSHOT, "xstore_priority": priority}


def render(snapshot: Path) -> dict[Path, str]:
    held = holdings(snapshot)
    files: dict[Path, str] = {}
    sources = []
    for store in sorted({s for stores in held.values() for s in stores}):
        tables = [
            {"name": e, "description": f"{store} native {e} records (frozen JSONL)."}
            for e, stores in sorted(held.items())
            if store in stores
        ]
        sources.append(
            {
                "name": store,
                "schema": store,
                "description": f"Frozen snapshot of {store}, read in place by DuckDB.",
                "config": {
                    "meta": {
                        "external_location": 'read_json_objects(\'{{ var("snapshot_dir") }}'
                        "/{schema}/{name}.jsonl', format='newline_delimited')"
                    }
                },
                "tables": tables,
            }
        )
    files[DBT / "models" / "staging" / "_sources.yml"] = HEADER.replace("--", "#") + yaml.safe_dump(
        {"version": 2, "sources": sources}, sort_keys=False, width=200
    )
    models = []
    for entity_type, stores in sorted(held.items()):
        key = ENTITY_TYPES[entity_type].key_field
        for store in stores:
            name = f"stg_{store}__{PLURAL[entity_type]}"
            m = load_mapping(store).for_entity(entity_type)
            files[DBT / "models" / "staging" / f"{name}.sql"] = staging_sql(
                store, entity_type, m, snapshot
            )
            models.append(
                {
                    "name": name,
                    "description": f"{store} {entity_type} mapped to canonical names and units.",
                    "columns": [
                        {"name": key, "data_tests": ["not_null"]},
                        {"name": "_type_drift", "data_tests": ["not_null"]},
                    ],
                }
            )
    files[DBT / "models" / "staging" / "_staging.yml"] = HEADER.replace("--", "#") + yaml.safe_dump(
        {"version": 2, "models": models}, sort_keys=False, width=200
    )
    project = {
        "name": "xstore",
        "version": "1.0.0",
        "config-version": 2,
        "profile": "xstore",
        "model-paths": ["models"],
        "macro-paths": ["macros"],
        "test-paths": ["tests"],
        "target-path": "target",
        "clean-targets": ["target"],
        "flags": {"send_anonymous_usage_stats": False},
        "vars": policy_vars(held),
        "models": {"xstore": {"+materialized": "table"}},
    }
    files[DBT / "dbt_project.yml"] = (
        "# Generated by scripts/gen_dbt_staging.py (priorities from policy/policy.yaml).\n"
        + yaml.safe_dump(project, sort_keys=False, width=200)
    )
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = ap.parse_args()
    files = render(ROOT / SNAPSHOT)
    stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
    if args.check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}")
        return 1 if stale else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text := files[p])
        print(f"wrote {p.relative_to(ROOT)} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
